// One paragraph per click. Keep the story independent of React and Electron.
function lines(text: string): Line[] {
  return text.trim().split('\n').map(paragraph => {
    const [speaker, ...rest] = paragraph.split('｜');
    return { speaker, text: rest.join('｜') };
  });
}

